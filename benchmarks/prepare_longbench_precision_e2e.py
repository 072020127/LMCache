"""Build a fixed LongBench manifest for MaKV precision-upgrade E2E tests.

The manifest contains the exact LongBench source fields, the prompt hash from
the production benchmark prompt builder, and the official metric name.  It
does not contain risk labels or oracle token selections; those must be
generated by the E2E runner at runtime.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any
import argparse
import hashlib
import json
import os

from transformers import AutoTokenizer

from benchmarks.longbench_makv_cachegen import (
    LongBenchExample,
    load_examples,
    prompt_ids,
    prompt_token_hash,
)
from benchmarks.longbench_official.adapter import metric_name


DEFAULT_LONGBENCH_ROOT = Path(
    os.environ.get(
        "LONGBENCH_ROOT", "/media/home/iic/mahaoyuan/datas/longbench"
    )
)
DEFAULT_MODEL = "/media/home/iic/mahaoyuan/models/Qwen3-8B"
DEFAULT_OUTPUT = Path(
    "experiments/makv_precision_e2e/longbench_e2e_manifest.jsonl"
)
DEFAULT_TASKS = (
    "hotpotqa",
    "2wikimqa",
    "musique",
    "qasper",
    "triviaqa",
)
DEFAULT_LENGTH_BINS = "1024-4096,4097-8192,8193-16384,16385-32768"
MANIFEST_VERSION = "makv_longbench_precision_e2e_v1"
PROMPT_BUILDER = "benchmarks.longbench_makv_cachegen.prompt_ids:v1"


@dataclass(frozen=True)
class LengthBin:
    label: str
    lower: int
    upper: int

    def contains(self, value: int) -> bool:
        return self.lower <= value <= self.upper


@dataclass(frozen=True)
class PreparedExample:
    task: str
    example: LongBenchExample
    source_path: str
    prompt_case_id: str
    prompt_token_hash: str
    prompt_token_count: int
    length_bin: LengthBin
    selection_key: str


def _parse_tasks(value: str, data_dir: Path) -> tuple[str, ...]:
    """Resolve a comma-separated task list, with ``all`` support."""
    if value.strip().lower() == "all":
        return tuple(sorted(path.stem for path in data_dir.glob("*.jsonl")))
    tasks = tuple(part.strip().lower() for part in value.split(",") if part.strip())
    if not tasks:
        raise ValueError("--tasks must not be empty")
    return tasks


def _parse_length_bins(value: str) -> tuple[LengthBin, ...]:
    """Parse inclusive ranges such as ``1024-4096,4097-8192``."""
    result: list[LengthBin] = []
    for raw_range in value.split(","):
        raw_range = raw_range.strip()
        if not raw_range:
            continue
        separator = "-" if "-" in raw_range else ":"
        parts = raw_range.split(separator)
        if len(parts) != 2:
            raise ValueError(
                f"invalid length range {raw_range!r}; expected LOWER-UPPER"
            )
        lower, upper = (int(part.strip()) for part in parts)
        if lower < 0 or upper < lower:
            raise ValueError(f"invalid length range {raw_range!r}")
        result.append(LengthBin(f"{lower}-{upper}", lower, upper))
    if not result:
        raise ValueError("--length-bins must contain at least one range")
    for left, right in zip(result, result[1:]):
        if right.lower <= left.upper:
            raise ValueError("--length-bins must not overlap")
    return tuple(result)


def _case_id(prompt_run_id: str, example_id: str) -> str:
    return hashlib.sha256(f"{prompt_run_id}:{example_id}".encode()).hexdigest()


def _find_bin(token_count: int, bins: tuple[LengthBin, ...]) -> LengthBin | None:
    return next((item for item in bins if item.contains(token_count)), None)


def _prepare_task(
    *,
    task: str,
    source_path: Path,
    tokenizer: Any,
    prompt_run_id: str,
    bins: tuple[LengthBin, ...],
    min_prompt_tokens: int,
    max_prompt_tokens: int,
    seed: int,
) -> list[PreparedExample]:
    examples = load_examples(source_path, task, -1, 0)
    prepared: list[PreparedExample] = []
    for example in examples:
        ids = prompt_ids(tokenizer, example, prompt_run_id, enable_thinking=False)
        token_count = len(ids)
        if token_count < min_prompt_tokens:
            continue
        if max_prompt_tokens > 0 and token_count > max_prompt_tokens:
            continue
        length_bin = _find_bin(token_count, bins)
        if length_bin is None:
            continue
        selection_key = hashlib.sha256(
            f"{seed}:{task}:{example.example_id}".encode()
        ).hexdigest()
        prepared.append(
            PreparedExample(
                task=task,
                example=example,
                source_path=str(source_path),
                prompt_case_id=_case_id(prompt_run_id, example.example_id),
                prompt_token_hash=prompt_token_hash(ids),
                prompt_token_count=token_count,
                length_bin=length_bin,
                selection_key=selection_key,
            )
        )
    return prepared


def _select_balanced(
    candidates: list[PreparedExample], samples_per_task: int
) -> list[PreparedExample]:
    """Select deterministically with round-robin length-bin balancing."""
    if len(candidates) < samples_per_task:
        raise ValueError(
            f"only {len(candidates)} eligible samples are available, but "
            f"{samples_per_task} were requested"
        )
    queues: dict[str, list[PreparedExample]] = {}
    bin_order: list[str] = []
    for candidate in sorted(candidates, key=lambda item: item.selection_key):
        label = candidate.length_bin.label
        if label not in queues:
            queues[label] = []
            bin_order.append(label)
        queues[label].append(candidate)

    selected: list[PreparedExample] = []
    while len(selected) < samples_per_task:
        progressed = False
        for label in bin_order:
            queue = queues[label]
            if queue:
                selected.append(queue.pop(0))
                progressed = True
                if len(selected) == samples_per_task:
                    break
        if not progressed:
            raise RuntimeError("balanced LongBench selection made no progress")
    return selected


def _record(
    item: PreparedExample,
    *,
    global_index: int,
    prompt_run_id: str,
    max_new_tokens: int,
    generation_seed: int,
    precision_scheme: str,
    bucket_ratios: tuple[float, ...],
    bucket_bits: tuple[int, ...],
    upgrade_rates: tuple[float, ...],
    window_tokens: int,
) -> dict[str, Any]:
    example = item.example
    return {
        "manifest_version": MANIFEST_VERSION,
        "sample_index": global_index,
        "task": item.task,
        "sample_id": example.example_id,
        "cache_group": f"longbench:{item.task}:{example.example_id}",
        "source_file": item.source_path,
        "context": example.context,
        "question": example.question,
        "answers": list(example.answers),
        "all_classes": list(example.all_classes),
        "source_length": example.length,
        "prompt_builder": PROMPT_BUILDER,
        "prompt_run_id": prompt_run_id,
        "prompt_case_id": item.prompt_case_id,
        "prompt_token_hash": item.prompt_token_hash,
        "prompt_token_count": item.prompt_token_count,
        "context_length_bucket": item.length_bin.label,
        "official_metric": metric_name(item.task),
        "generation": {
            "temperature": 0.0,
            "top_p": 1.0,
            "seed": generation_seed,
            "max_new_tokens": max_new_tokens,
            "enable_thinking": False,
        },
        "makv_experiment": {
            "precision_scheme": precision_scheme,
            "bucket_ratios": list(bucket_ratios),
            "bucket_bits": list(bucket_bits),
            "upgrade_rates": list(upgrade_rates),
            "window_tokens": window_tokens,
            "risk_token_index_required": True,
            "risk_labels_generated_at_runtime": True,
        },
    }


def _write_json(path: Path, payload: Any, *, overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"refusing to overwrite {path}; use --overwrite")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def build_manifest(args: argparse.Namespace) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    data_dir = Path(args.longbench_root) / "data"
    if not data_dir.is_dir():
        raise FileNotFoundError(f"LongBench data directory not found: {data_dir}")
    tasks = _parse_tasks(args.tasks, data_dir)
    bins = _parse_length_bins(args.length_bins)
    tokenizer = AutoTokenizer.from_pretrained(
        args.tokenizer, local_files_only=True
    )

    records: list[dict[str, Any]] = []
    task_summary: dict[str, Any] = {}
    for task in tasks:
        source_path = data_dir / f"{task}.jsonl"
        if not source_path.is_file():
            raise FileNotFoundError(f"LongBench task file not found: {source_path}")
        candidates = _prepare_task(
            task=task,
            source_path=source_path,
            tokenizer=tokenizer,
            prompt_run_id=args.prompt_run_id,
            bins=bins,
            min_prompt_tokens=args.min_prompt_tokens,
            max_prompt_tokens=args.max_prompt_tokens,
            seed=args.seed,
        )
        selected = _select_balanced(candidates, args.samples_per_task)
        task_records = [
            _record(
                item,
                global_index=len(records) + index,
                prompt_run_id=args.prompt_run_id,
                max_new_tokens=args.max_new_tokens,
                generation_seed=args.generation_seed,
                precision_scheme=args.precision_scheme,
                bucket_ratios=args.bucket_ratios,
                bucket_bits=args.bucket_bits,
                upgrade_rates=args.upgrade_rates,
                window_tokens=args.window_tokens,
            )
            for index, item in enumerate(selected)
        ]
        records.extend(task_records)
        task_summary[task] = {
            "source_rows": len(load_examples(source_path, task, -1, 0)),
            "eligible_rows": len(candidates),
            "selected_rows": len(selected),
            "metric": metric_name(task),
            "length_bins": dict(
                Counter(record["context_length_bucket"] for record in task_records)
            ),
            "prompt_tokens": {
                "min": min(record["prompt_token_count"] for record in task_records),
                "max": max(record["prompt_token_count"] for record in task_records),
                "mean": sum(
                    record["prompt_token_count"] for record in task_records
                )
                / len(task_records),
            },
        }

    metadata = {
        "manifest_version": MANIFEST_VERSION,
        "longbench_root": str(Path(args.longbench_root).resolve()),
        "tokenizer": str(Path(args.tokenizer).resolve()),
        "tasks": list(tasks),
        "samples_per_task": args.samples_per_task,
        "total_samples": len(records),
        "selection_seed": args.seed,
        "prompt_run_id": args.prompt_run_id,
        "prompt_builder": PROMPT_BUILDER,
        "length_bins": [item.label for item in bins],
        "min_prompt_tokens": args.min_prompt_tokens,
        "max_prompt_tokens": args.max_prompt_tokens,
        "generation": {
            "temperature": 0.0,
            "top_p": 1.0,
            "seed": args.generation_seed,
            "max_new_tokens": args.max_new_tokens,
            "enable_thinking": False,
        },
        "makv_experiment": {
            "precision_scheme": args.precision_scheme,
            "bucket_ratios": list(args.bucket_ratios),
            "bucket_bits": list(args.bucket_bits),
            "upgrade_rates": list(args.upgrade_rates),
            "window_tokens": args.window_tokens,
            "residual_dtypes": ["float16", "float32"],
            "risk_selection": ["CONF", "margin-only", "matched-random", "oracle"],
            "risk_labels_generated_at_runtime": True,
        },
        "task_summary": task_summary,
    }
    return records, metadata


def _parse_csv_floats(value: str) -> tuple[float, ...]:
    return tuple(float(part.strip()) for part in value.split(",") if part.strip())


def _parse_csv_ints(value: str) -> tuple[int, ...]:
    return tuple(int(part.strip()) for part in value.split(",") if part.strip())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--longbench-root", default=str(DEFAULT_LONGBENCH_ROOT))
    parser.add_argument("--tokenizer", default=DEFAULT_MODEL)
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--tasks", default=",".join(DEFAULT_TASKS))
    parser.add_argument("--samples-per-task", type=int, default=100)
    parser.add_argument("--length-bins", default=DEFAULT_LENGTH_BINS)
    parser.add_argument("--min-prompt-tokens", type=int, default=1024)
    parser.add_argument("--max-prompt-tokens", type=int, default=32768)
    parser.add_argument(
        "--prompt-run-id", default="longbench-makv-precision-e2e-v1"
    )
    parser.add_argument("--seed", type=int, default=20260829)
    parser.add_argument("--generation-seed", type=int, default=123)
    parser.add_argument("--max-new-tokens", type=int, default=1024)
    parser.add_argument("--precision-scheme", default="kv_separate_4tier")
    parser.add_argument("--bucket-ratios", type=_parse_csv_floats, default=(0.10, 0.20, 0.50, 0.20))
    parser.add_argument("--bucket-bits", type=_parse_csv_ints, default=(16, 8, 4, 2))
    parser.add_argument("--upgrade-rates", type=_parse_csv_floats, default=(0.01, 0.05, 0.10, 0.20))
    parser.add_argument("--window-tokens", type=int, default=16)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    if args.samples_per_task <= 0:
        raise SystemExit("--samples-per-task must be positive")
    if len(args.bucket_ratios) != len(args.bucket_bits):
        raise SystemExit("--bucket-ratios and --bucket-bits must have equal length")
    if abs(sum(args.bucket_ratios) - 1.0) > 1e-6:
        raise SystemExit("--bucket-ratios must sum to 1.0")
    if args.window_tokens <= 0:
        raise SystemExit("--window-tokens must be positive")

    records, metadata = build_manifest(args)
    output = Path(args.output)
    if output.exists() and not args.overwrite:
        raise SystemExit(f"refusing to overwrite {output}; use --overwrite")
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True))
            handle.write("\n")

    metadata_path = output.with_suffix(".meta.json")
    summary_path = output.with_suffix(".summary.json")
    _write_json(metadata_path, metadata, overwrite=args.overwrite)
    _write_json(
        summary_path,
        {
            "manifest": str(output),
            "metadata": str(metadata_path),
            "total_samples": len(records),
            "tasks": metadata["task_summary"],
        },
        overwrite=args.overwrite,
    )
    print(json.dumps({"manifest": str(output), **metadata}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
